def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    proc = subprocess.Popen(
        ["curl", "-s", "--max-time", "420", URL],
        stdout=subprocess.PIPE,
    )
    dec = None
    buf = b""
    lines = []
    seen = set()
    total_read = 0
    block = []
    blocks = 0
    with open(OUT, "w", encoding="utf-8") as f:
        # Сид-диалоги повторяем: так модель выучивает роли «П:/B:» и своё
        # поведение (обучение на данных, не заготовки в рантайме).
        for rep in range(60):
            for q, a in SEED:
                f.write(f"П: {q}\nB: {a}\n\n")
                blocks += 1
        while True:
            chunk = proc.stdout.read(1 << 20)
            if not chunk:
                break
            total_read += len(chunk)
            buf += chunk
            if dec is None:
                import zlib
                dec = zlib.decompressobj(31)
            data = dec.decompress(buf)
            buf = b""
            for raw in data.split(b"\n"):
                try:
                    line = raw.decode("utf-8").strip()
                except UnicodeDecodeError:
                    continue
                if not ok(line):
                    if block:
                        if BLOCK_MIN <= len(block) <= BLOCK_MAX and len(set(block)) == len(block):
                            f.write("<doc>\n")
                            for i, t in enumerate(block):
                                f.write(("П: " if i % 2 == 0 else "B: ") + t + "\n")
                            f.write("\n")
                            blocks += 1
                        block = []
                    continue
                key = line.lower()
                if key in seen:
                    if block:
                        if BLOCK_MIN <= len(block) <= BLOCK_MAX and len(set(block)) == len(block):
                            f.write("<doc>\n")
                            for i, t in enumerate(block):
                                f.write(("П: " if i % 2 == 0 else "B: ") + t + "\n")
                            f.write("\n")
                            blocks += 1
                        block = []
                    continue
                seen.add(key)
                block.append(line)
                lines.append(line)
                if len(lines) >= TARGET_LINES:
                    break
            if len(lines) >= TARGET_LINES:
                proc.kill()
                break
            if total_read > (655 << 20):
                break
    size = os.path.getsize(OUT)
    print(f"строк диалогов: {len(lines)}, блоков: {blocks}, размер: {size/1e6:.1f} МБ, скачано: {total_read>>20} МБ")

if __name__ == "__main__":
    main()
