OUT = os.path.join(HERE, "data", "corpus.txt")
TARGET_LINES = 210_000      # строк диалогов (достаточно для маленького GPT)
BLOCK_MIN, BLOCK_MAX = 2, 6

CYR = re.compile(r"[а-яё]")
LAT = re.compile(r"[a-z]")
BAD = re.compile(r"(http|www\.|@|\.com|\.ru\b|&)", re.I)

def ok(line: str) -> bool:
    """Фильтр строки субтитров."""
    n = len(line)
    if n < 15 or n > 160:
        return False
    if BAD.search(line):
        return False
    letters = sum(ch.isalpha() for ch in line)
    if letters < n * 0.62:
        return False
    cyr = len(CYR.findall(line))
    lat = len(LAT.findall(line))
    if cyr < lat:                      # русский, не транслит
        return False
    if line.upper() == line and cyr > 2:
        return False                   # КАПС
    digits = sum(ch.isdigit() for ch in line)
    if digits > 2:
        return False
    return True

