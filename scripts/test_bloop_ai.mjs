/* Тест BLOOP AI: точность классификатора (holdout 85/15) + примеры ответов. */
import { createBloopAI, selfTest } from '../src/ai/engine.js';

const t0 = Date.now();
const { accuracy, tested, errors } = selfTest();
console.log(`=== Классификатор ===`);
console.log(`точность на holdout (${tested} фраз): ${(accuracy * 100).toFixed(1)}%`);
if (errors.length) console.log('ошибки:', errors.slice(0, 5));
console.log(`время: ${Date.now() - t0} мс`);

const ai = createBloopAI();
console.log(`\n=== Обучение ===\nфраз: ${ai.examplesCount}, финальный loss: ${ai.finalLoss.toFixed(4)}`);

console.log(`\n=== Примеры ответов ===`);
const ctx = {
  name: 'Ваня',
  tags: ['спорт', 'музыка', 'фото'],
  trends: ['закат', 'школа', 'клипы'],
  texts: [
    'Сегодня был отличный день, погулял с друзьями и сделал классные фото на закате.',
    'Качал ноги в зале, теперь еле хожу, но доволен.',
    'Новая музыка вообще зашла, рекомендую всем этот альбом.',
    'Снял клип на телефон и получилось даже лучше, чем ожидал.',
    'Много думал про новую тему для поста и наконец придумал.',
    'Люблю вечера, когда никто не трогает и можно спокойно писать код.',
    'Завтра планирую выбраться на пробежку, если погода не подведёт.',
  ],
};
const questions = [
  'привет',
  'что ты умеешь',
  'ты нейросеть?',
  'придумай пост про осень',
  'напиши в моем стиле',
  'подбери хэштеги для фото с моря',
  'идея клипа',
  'оцени пост: Сегодня купил новый телефон! Делал фото весь день, какой чудесный день? #лайфстайл #техно #фото #день',
  'как позвонить другу',
  'ещё',
];
for (const q of questions) {
  const { reply, intent, confidence } = ai.answer(q, ctx);
  console.log(`\nQ: ${q}\n  [${intent} ${(confidence * 100).toFixed(0)}%] ${reply.replace(/\n/g, ' | ').slice(0, 220)}`);
}
